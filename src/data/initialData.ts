function createJuzMap(mutqinJuzs: number[], prosesJuzs: number[]): Record<number, JuzStatus> {
  const map: Record<number, JuzStatus> = {};
  for (let i = 1; i <= 30; i++) {
    if (mutqinJuzs.includes(i)) {
      map[i] = 'mutqin';
    } else if (prosesJuzs.includes(i)) {
      map[i] = 'proses';
    } else {
      map[i] = 'belum';
    }
  }
  return map;
}

